// Generates the engine-independent C++ weapon table (TFWeaponTable.h) from data/pilot_weapons.csv
// and data/ordnance_abilities.csv. Usage: node weaponheader.js <dataDir> <outHeader>
const fs = require('fs');
const path = require('path');
const [dataDir, outHeader] = process.argv.slice(2);

function csv(file) {
  const text = fs.readFileSync(path.join(dataDir, file), 'utf8').trim();
  const [head, ...lines] = text.split('\n');
  const cols = head.split(',');
  const split = l => (l.match(/("([^"]|"")*")/g) || []).map(s => s.slice(1, -1).replace(/""/g, '"'));
  return lines.map(l => Object.fromEntries(split(l).map((v, i) => [cols[i], v])));
}

const f = v => {
  const n = parseFloat(v);
  return Number.isFinite(n) ? (Number.isInteger(n) ? `${n}.0f` : `${n}f`) : '0.0f';
};
const i = v => {
  const n = parseInt(v, 10);
  return Number.isFinite(n) ? String(n) : '0';
};
const s = v => JSON.stringify(v ?? '');

const weapons = csv('pilot_weapons.csv').filter(r => r.category !== 'Melee');
const ordnance = csv('ordnance_abilities.csv');

const wRows = weapons.map(r => `\t{ ${[
  s(r.weapon), s(r.file), s(r.category),
  f(r.fire_rate), i(r.burst_count), f(r.burst_delay_s), r.semi_auto === '1' ? 'true' : 'false',
  i(r.pellets_n), r.shotgun_blast === '1' ? 'true' : 'false',
  f(r.dmg_near), f(r.dmg_far), f(r.dmg_very_far), f(r.near_dist), f(r.far_dist), f(r.very_far_dist),
  f(r.headshot_scale), f(r.titanarmor_near), f(r.explosion_dmg), f(r.explosion_radius),
  i(r.clip), f(r.ammo_per_shot || 1), f(r.reload_s), f(r.reload_empty_s),
  f(r.ads_in_s), f(r.ads_out_s), f(r.ads_fov), f(r.ads_move_scale),
  f(r.deploy_s), f(r.holster_s), f(r.raise_s),
  f(r.spread_hip), f(r.spread_hip_max_kick), f(r.spread_ads), f(r.projectile_speed), f(r.charge_time),
].join(', ')} },`).join('\n');

const oRows = ordnance.map(r => `\t{ ${[
  s(r.name), s(r.file), f(r.impact_dmg), f(r.explosion_dmg), f(r.explosion_dmg_titan),
  f(r.inner_radius), f(r.radius), f(r.fuse_s), f(r.charges), f(r.cooldown_s), f(r.fire_duration_s),
].join(', ')} },`).join('\n');

const header = `// GENERATED by tools/node/weaponheader.js from data/pilot_weapons.csv and data/ordnance_abilities.csv.
// Do not hand-edit; regenerate instead. Engine-independent (no Unreal headers).
//
// Every value is [D]: read verbatim from the shipped weapon keyvalues (MP_BASE applied), except
//   PelletsPerShot for the Mastiff/Mozambique/Double-barrel, which comes from the weapon scripts [D],
//   and Charges/CooldownSeconds in the ordnance table, which are computed [C].
// Distances are Titanfall units (inches), times in seconds, angles in degrees.
#pragma once

#include <cstddef>

namespace TF
{
	struct WeaponStats
	{
		const char* Name;
		const char* File;
		const char* Category;
		float FireRate;            // shots per second (cap for semi-auto)
		int BurstCount;            // 1 = not a burst weapon
		float BurstDelay;          // seconds between bursts
		bool bSemiAuto;
		int PelletsPerShot;        // bolts/pellets per trigger pull; ignored when bShotgunBlast
		bool bShotgunBlast;        // EVA-8: one distance-scaled hit per target in the cone
		float DamageNear;
		float DamageFar;
		float DamageVeryFar;       // 0 = none
		float NearDistance;
		float FarDistance;
		float VeryFarDistance;     // 0 = none
		float HeadshotScale;
		float DamageNearTitanArmor;
		float ExplosionDamage;     // only applies when ExplosionRadius > 0
		float ExplosionRadius;
		int MagazineSize;
		float AmmoPerShot;
		float ReloadTime;
		float ReloadEmptyTime;
		float AdsInTime;
		float AdsOutTime;
		float AdsFov;
		float AdsMoveSpeedScale;
		float DeployTime;
		float HolsterTime;
		float RaiseTime;
		float SpreadHip;
		float SpreadHipMaxKick;
		float SpreadAds;
		float ProjectileSpeed;     // 0 = hitscan
		float ChargeTime;
	};

	struct OrdnanceStats
	{
		const char* Name;
		const char* File;
		float ImpactDamage;
		float ExplosionDamage;
		float ExplosionDamageTitan;
		float InnerRadius;
		float OuterRadius;
		float FuseTime;
		float Charges;             // [C] clip / ammo_per_shot
		float CooldownSeconds;     // [C] ammo_per_shot / regen rate (per charge)
		float Duration;
	};

	inline constexpr WeaponStats PilotWeapons[] =
	{
${wRows}
	};
	inline constexpr std::size_t NumPilotWeapons = sizeof(PilotWeapons) / sizeof(PilotWeapons[0]);

	inline constexpr OrdnanceStats PilotOrdnance[] =
	{
${oRows}
	};
	inline constexpr std::size_t NumPilotOrdnance = sizeof(PilotOrdnance) / sizeof(PilotOrdnance[0]);
}
`;
fs.mkdirSync(path.dirname(outHeader), { recursive: true });
fs.writeFileSync(outHeader, header.replace(/\r?\n/g, '\n'));
console.log(`wrote ${outHeader}: ${weapons.length} weapons, ${ordnance.length} ordnance`);
