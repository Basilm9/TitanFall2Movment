// Generates Public/TFPilotSettingsUE.h (Unreal USTRUCT mirrors of TFPilotSettings and
// TFMovementConVars) from Public/TFMovementCore.h, so the two stay in sync.
//
//   node tools/node/gen_settings_ue.js        (from the repo root)
//
// Field lines in the core structs must look like:   <type> <Name> = <default>; // <tag + comment>
// and "// @group <Name>" lines start a category.

'use strict';
const fs = require('fs');
const path = require('path');

const src = path.join(__dirname, '..', '..', 'examples', 'unreal', 'Plugins', 'TFMovement', 'Source', 'TFMovement', 'Public');
const core = fs.readFileSync(path.join(src, 'TFMovementCore.h'), 'utf8');

function parseStruct(name) {
  const start = core.indexOf(`struct ${name}\n{`);
  if (start < 0) throw new Error(`struct ${name} not found`);
  const end = core.indexOf('\n};', start);
  const body = core.slice(start, end).split('\n');
  const fields = [];
  let group = 'General';
  for (const line of body) {
    const g = line.match(/^\s*\/\/\s*@group\s+(\w+)/);
    if (g) { group = g[1]; continue; }
    const m = line.match(/^\s*(float|bool|ETFWallrunAdsType)\s+(\w+)\s*=\s*([^;]+);\s*\/\/\s*(.*)$/);
    if (m) fields.push({ type: m[1], name: m[2], def: m[3].trim(), comment: m[4].trim(), group });
  }
  return fields;
}

const esc = (s) => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
const ueType = (t) => (t === 'ETFWallrunAdsType' ? 'ETFWallrunAdsTypeUE' : t);
const ueDefault = (f) => (f.type === 'ETFWallrunAdsType' ? f.def.replace('ETFWallrunAdsType::', 'ETFWallrunAdsTypeUE::') : f.def);

function emitStruct(ueName, coreName, fields, categoryRoot, comment) {
  const out = [];
  out.push(`// ${comment}`);
  out.push('USTRUCT(BlueprintType)');
  out.push(`struct TFMOVEMENT_API ${ueName}`);
  out.push('{');
  out.push('\tGENERATED_BODY()');
  out.push('');
  let lastGroup = null;
  for (const f of fields) {
    if (f.group !== lastGroup) {
      if (lastGroup !== null) out.push('');
      out.push(`\t// ---- ${f.group} ----`);
      lastGroup = f.group;
    }
    out.push(`\tUPROPERTY(EditAnywhere, BlueprintReadWrite, Category = "${categoryRoot}|${f.group}", meta = (ToolTip = "${esc(f.comment)}"))`);
    out.push(`\t${ueType(f.type)} ${f.name} = ${ueDefault(f)}; // ${f.comment}`);
  }
  out.push('');
  out.push(`\t/** Copies every field into the engine-independent struct. */`);
  out.push(`\tvoid ToCore(${coreName}& Out) const`);
  out.push('\t{');
  for (const f of fields) {
    if (f.type === 'ETFWallrunAdsType') out.push(`\t\tOut.${f.name} = static_cast<ETFWallrunAdsType>(static_cast<int32_t>(${f.name}));`);
    else out.push(`\t\tOut.${f.name} = ${f.name};`);
  }
  out.push('\t}');
  out.push('');
  out.push(`\t/** Copies every field from the engine-independent struct. */`);
  out.push(`\tvoid FromCore(const ${coreName}& In)`);
  out.push('\t{');
  for (const f of fields) {
    if (f.type === 'ETFWallrunAdsType') out.push(`\t\t${f.name} = static_cast<ETFWallrunAdsTypeUE>(static_cast<uint8>(In.${f.name}));`);
    else out.push(`\t\t${f.name} = In.${f.name};`);
  }
  out.push('\t}');
  out.push('};');
  return out.join('\n');
}

const settings = parseStruct('TFPilotSettings');
const convars = parseStruct('TFMovementConVars');

const header = `// TFPilotSettingsUE.h
// GENERATED by tools/node/gen_settings_ue.js from TFMovementCore.h - do not edit by hand.
//
// Unreal-reflected mirrors of TFPilotSettings and TFMovementConVars. All values are in Titanfall
// units (inches, u/s, seconds); only positions and velocities are converted at the component
// boundary. Tooltips carry the source tag: [D] shipped .set value, [R] code default / ConVar,
// [C] computed, [I] inferred, [?] unknown.

#pragma once

#include "CoreMinimal.h"
#include "TFMovementCore.h"
#include "TFPilotSettingsUE.generated.h"

UENUM(BlueprintType)
enum class ETFWallrunAdsTypeUE : uint8
{
	None = 0 UMETA(DisplayName = "None (ADS cancelled)"),
	WallHang = 1 UMETA(DisplayName = "Wallhang"),
	Ads = 2 UMETA(DisplayName = "ADS (aim only)")
};

${emitStruct('FTFPilotSettingsUE', 'TFPilotSettings', settings, 'TF Pilot', 'Per-class pilot settings. Defaults = shipped MP pilot values (TITANFALL2_MOVEMENT.md sec.0).')}

${emitStruct('FTFMovementConVarsUE', 'TFMovementConVars', convars, 'TF ConVars', 'Server ConVars (registered defaults, [R]).')}
`;

const outPath = path.join(src, 'TFPilotSettingsUE.h');
fs.writeFileSync(outPath, header.replace(/\r?\n/g, '\n'));
console.log(`wrote ${outPath}: ${settings.length} settings, ${convars.length} convars`);
